"""Run Python transforms on the inputs declared by a Nix stage."""

from __future__ import annotations

import json
import os
import re
import shutil
import stat
import subprocess
import sys
from importlib import import_module
from pathlib import Path
from typing import TypedDict


class ToolPin(TypedDict):
    executable: str
    module: str
    version: str
    versionArgs: list[str]


class StagePlan(TypedDict):
    name: str
    transform: str
    inputs: dict[str, str]
    outputs: dict[str, str]
    configuration: dict[str, object]
    pins: list[ToolPin]


def verify_tool(pin: ToolPin) -> None:
    """Require the declared full version token from the selected executable."""
    command = [pin["executable"], *pin["versionArgs"]]
    result = subprocess.run(  # noqa: S603 - the pinned stage controls the tool and probe.
        command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, check=True
    )
    version = re.escape(pin["version"])
    boundary = r"[\w.+-]"
    if re.search(rf"(?<!{boundary}){version}(?!{boundary})", result.stdout) is None:
        raise RuntimeError(f"{pin['module']} did not report required version {pin['version']}")


def _copy(source: Path, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    if source.is_dir():
        shutil.copytree(source, target, symlinks=True)
    else:
        shutil.copy(source, target)


def _make_writable(path: Path) -> None:
    if not path.is_symlink():
        path.chmod(stat.S_IMODE(path.stat().st_mode) | stat.S_IWUSR)


def _report(log: Path) -> None:
    if log.is_file():
        with log.open(encoding="utf-8", errors="replace") as stream:
            shutil.copyfileobj(stream, sys.stderr)


def _stage_input(source: Path, target: Path) -> None:
    _copy(source, target)
    _make_writable(target)
    for entry in target.rglob("*"):
        _make_writable(entry)


def _valid_output(path: Path, work: Path) -> bool:
    if path.is_symlink() or not path.resolve().is_relative_to(work):
        return False
    if path.is_dir():
        return all(
            not item.is_symlink() and (item.is_file() or item.is_dir()) for item in path.rglob("*")
        )
    return path.is_file()


def run(plan: StagePlan, work: Path, log: Path) -> None:
    """Stage inputs, run the transform, and verify its files or directories."""
    module, function = plan["transform"].split(":")
    transform = getattr(import_module(module), function)
    work.mkdir(parents=True)
    for filename, source in plan["inputs"].items():
        _stage_input(Path(source), work / filename)
    transform(work, log, plan["configuration"])
    for filename in plan["outputs"].values():
        if not _valid_output(work / filename, work):
            raise RuntimeError(f"Stage {plan['name']} did not produce {filename}")


def main() -> None:
    """Install the verified artifacts in the separate Nix outputs."""
    plan_file = Path(os.environ["stagePlanPath"])  # noqa: SIM112 - generated by Nix
    plan: StagePlan = json.loads(plan_file.read_bytes())
    work = Path.cwd() / "work"
    log = Path.cwd() / "stage.log"
    try:
        for pin in plan["pins"]:
            verify_tool(pin)
        run(plan, work, log)
        for output, filename in plan["outputs"].items():
            _copy(work / filename, Path(os.environ[output]) / filename)
    finally:
        _report(log)


if __name__ == "__main__":
    main()
