"""Run an importable Python transform with the files declared by its Nix stage."""

from __future__ import annotations

import json
import os
import re
import shutil
import stat
import subprocess
import sys
from importlib import import_module
from pathlib import Path
from typing import TypedDict


class ToolPin(TypedDict):
    executable: str
    module: str
    version: str
    versionArgs: list[str]


class StagePlan(TypedDict):
    name: str
    transform: str
    inputs: dict[str, str]
    outputs: dict[str, str]
    configuration: dict[str, object]
    pins: list[ToolPin]


def verify_tool(pin: ToolPin) -> None:
    """Require the declared full version token from the selected executable."""
    command = [pin["executable"], *pin["versionArgs"]]
    result = subprocess.run(  # noqa: S603 - the pinned stage controls the tool and probe.
        command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, check=True
    )
    version = re.escape(pin["version"])
    boundary = r"[\w.+-]"
    if re.search(rf"(?<!{boundary}){version}(?!{boundary})", result.stdout) is None:
        raise RuntimeError(f"{pin['module']} did not report required version {pin['version']}")


def run(plan: StagePlan, work: Path, log: Path) -> None:
    """Stage editable copies of the inputs, invoke Python, and verify the outputs."""
    for pin in plan["pins"]:
        verify_tool(pin)
    module, function = plan["transform"].split(":")
    transform = getattr(import_module(module), function)
    work.mkdir()
    for filename, source in plan["inputs"].items():
        target = work / filename
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(source, target)
        target.chmod(stat.S_IMODE(target.stat().st_mode) | stat.S_IWUSR)
    transform(work, log, plan["configuration"])
    for filename in plan["outputs"].values():
        path = work / filename
        if not path.is_file() or path.is_symlink() or not path.resolve().is_relative_to(work):
            raise RuntimeError(f"Stage {plan['name']} did not produce {filename}")


def main() -> None:
    """Install the verified files in the separate Nix outputs."""
    plan_file = Path(os.environ["stagePlanPath"])  # noqa: SIM112 - generated by Nix
    plan: StagePlan = json.loads(plan_file.read_bytes())
    work = Path.cwd() / "work"
    log = Path.cwd() / "stage.log"
    try:
        run(plan, work, log)
        for output, filename in plan["outputs"].items():
            target = Path(os.environ[output]) / filename
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(work / filename, target)
    finally:
        if log.is_file():
            with log.open(encoding="utf-8", errors="replace") as stream:
                shutil.copyfileobj(stream, sys.stderr)


if __name__ == "__main__":
    main()
